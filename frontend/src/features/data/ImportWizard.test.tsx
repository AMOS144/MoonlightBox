import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, test, vi } from 'vitest'
import { MemoryRouter } from 'react-router-dom'
import { ImportWizard } from './ImportWizard'
import { TestThemeProvider } from '../../test/TestThemeProvider'
const preview = { id: 'preview-1', message_count: 2, participants: ['甲', '乙'], time_range: null, kind_counts: {}, sample_messages: [], errors: [] }
afterEach(() => { cleanup(); sessionStorage.clear(); vi.unstubAllGlobals() })
function mount(stage: 'import' | 'participants' = 'import') {
  return render(<TestThemeProvider><MemoryRouter><ImportWizard projectId="p1" stage={stage} /></MemoryRouter></TestThemeProvider>)
}
test('旧预览中的系统发送者也不会出现在人物选项中', () => {
  sessionStorage.setItem('import-preview:p1', JSON.stringify({ ...preview, participants: ['甲', '乙', '系统'] }))
  sessionStorage.setItem('import-self:p1', JSON.stringify('系统'))
  mount('participants')
  const input = screen.getByRole('combobox', { name: '我' })
  expect(input).toHaveValue('')
  fireEvent.click(input)
  expect(screen.queryByRole('option', { name: '系统' })).not.toBeInTheDocument()
  expect(screen.getByRole('option', { name: '甲' })).toBeInTheDocument()
  expect(screen.getByRole('button', { name: '确认人物并导入' })).toBeDisabled()
})
test('上传只到解析预览，然后交接人物确认，不启动 Job 轮询', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify(preview))))
  mount()
  fireEvent.change(screen.getByLabelText('WxEcho 导出目录'), { target: { files: [new File(['data'], 'chat.csv')] } })
  fireEvent.click(screen.getByRole('button', { name: '扫描并预览' }))
  expect(await screen.findByRole('link', { name: '记录已解析，确认人物与资料' })).toHaveAttribute('href', '/projects/p1/setup/participants')
  expect(screen.getByText(/已解析，尚未保存/)).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: '扫描并预览' })).not.toBeInTheDocument()
  expect(screen.queryByText(/导入完成/)).not.toBeInTheDocument()
  expect(fetch).toHaveBeenCalledTimes(1)
})
test('刷新后恢复已上传预览，正式确认后只报告保存结果', async () => {
  sessionStorage.setItem('import-preview:p1', JSON.stringify(preview))
  vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({ import_id: 'i', message_count: 2, created: true, world_job_id: 'j' }))))
  mount('participants')
  fireEvent.click(screen.getByRole('combobox', { name: '我' }))
  fireEvent.click(screen.getByRole('option', { name: '甲' }))
  fireEvent.click(screen.getByRole('combobox', { name: '目标人物' }))
  fireEvent.click(screen.getByRole('option', { name: '乙' }))
  fireEvent.click(screen.getByRole('button', { name: '确认人物并导入' }))
  expect(await screen.findByText(/导入完成，已保存 2 条消息/)).toBeInTheDocument()
  expect(fetch).toHaveBeenCalledTimes(1)
  expect(screen.queryByText(/关键节点/)).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: '确认人物并导入' })).not.toBeInTheDocument()
})
test('选一方自动补齐另一方，选定后仍可从两边交换并保存', async () => {
  sessionStorage.setItem('import-preview:p1', JSON.stringify(preview))
  mount('participants')
  fireEvent.click(screen.getByRole('combobox', { name: '我' }))
  fireEvent.click(screen.getByRole('option', { name: '甲' }))
  expect(screen.getByRole('combobox', { name: '目标人物' })).toHaveValue('乙')
  fireEvent.click(screen.getByRole('combobox', { name: '目标人物' }))
  fireEvent.click(screen.getByRole('option', { name: '甲' }))
  expect(screen.getByRole('combobox', { name: '我' })).toHaveValue('乙')
  expect(screen.getByRole('combobox', { name: '目标人物' })).toHaveValue('甲')
  fireEvent.click(screen.getByRole('combobox', { name: '我' }))
  fireEvent.click(screen.getByRole('option', { name: '甲' }))
  expect(screen.getByRole('combobox', { name: '目标人物' })).toHaveValue('乙')
  expect(JSON.parse(sessionStorage.getItem('import-self:p1')!)).toBe('甲')
  expect(JSON.parse(sessionStorage.getItem('import-target:p1')!)).toBe('乙')
  expect(screen.getByRole('button', { name: '确认人物并导入' })).toBeEnabled()
})
test('扫描失败保留重试入口', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => new Response('{}', { status: 500 })))
  mount()
  fireEvent.change(screen.getByLabelText('WxEcho 导出目录'), { target: { files: [new File(['data'], 'chat.csv')] } })
  fireEvent.click(screen.getByRole('button', { name: '扫描并预览' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('扫描失败')
  expect(screen.getByRole('button', { name: '扫描并预览' })).toBeEnabled()
})
